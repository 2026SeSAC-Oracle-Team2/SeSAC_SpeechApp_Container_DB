-- -----------------------------------------------------------
-- IMAGE_RESOURCE
-- Object Storage 메타데이터만 저장, 실제 파일은 Backend SDK가 관리
-- -----------------------------------------------------------
CREATE TABLE speechapp_content.image_resource (
    image_id        NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image_name      VARCHAR2(200) NOT NULL,
    bucket_path     VARCHAR2(500) NOT NULL,
    problem_type    VARCHAR2(20)  NOT NULL,
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_image_resource_problem_type
        CHECK (problem_type IN ('DESCRIBE', 'CHOOSE'))
);

CREATE INDEX idx_image_resource_type ON speechapp_content.image_resource(problem_type);

-- -----------------------------------------------------------
-- IMAGE_TAG
-- '그림 보고 설명하기' 정답 태그
-- -----------------------------------------------------------
CREATE TABLE speechapp_content.image_tag (
    tag_id          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image_id        NUMBER(19) NOT NULL,
    tag_text        VARCHAR2(100) NOT NULL,
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_image_tag_image_id
        FOREIGN KEY (image_id) REFERENCES speechapp_content.image_resource(image_id)
);

CREATE INDEX idx_image_tag_image ON speechapp_content.image_tag(image_id);

-- -----------------------------------------------------------
-- IMAGE_HINT
-- '설명 보고 그림 맞추기' 힌트
-- -----------------------------------------------------------
CREATE TABLE speechapp_content.image_hint (
    hint_id         NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image_id        NUMBER(19) NOT NULL,
    hint_type       VARCHAR2(20)  NOT NULL,
    hint_text       VARCHAR2(200) NOT NULL,
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_image_hint_image_id
        FOREIGN KEY (image_id) REFERENCES speechapp_content.image_resource(image_id),
    CONSTRAINT chk_image_hint_type
        CHECK (hint_type IN ('CHOSUNG', 'ASSOCIATION'))
);

CREATE INDEX idx_image_hint_image ON speechapp_content.image_hint(image_id);
CREATE INDEX idx_image_hint_type  ON speechapp_content.image_hint(hint_type);
